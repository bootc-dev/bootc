//! GRUB menu entries for Type1 (BLS) boot entries, for a GRUB without `blscfg`.
//!
//! On the BLS path bootc writes `loader/entries/*.conf` and nothing else,
//! expecting GRUB's `blscfg` command to turn them into a menu. Some distributions'
//! signed GRUB images do not build that command in, and under Secure Boot they
//! refuse to load it as a module (Ubuntu's signed GRUB is one). Such a GRUB keeps
//! booting whatever menu it was given at install time, so an upgrade stages,
//! reboots and silently comes back on the old deployment.
//!
//! This writes the menu `blscfg` would have produced to `grub2/bootc-bls.cfg`,
//! every time the live entries change. The GRUB configuration has to source it;
//! nothing here edits `grub.cfg`. A GRUB that has `blscfg` and does not source
//! the file is unaffected.
//!
//! Not `grub2/user.cfg`: its existence is what marks a GRUB node as booting UKIs
//! (see `list_bootloader_entries`), and garbage collection reads it as such.

use std::fmt::Write as _;
use std::io::{Read, Write};

use anyhow::{Context, Result};
use cap_std_ext::cap_std::fs::Dir;
use cap_std_ext::dirext::CapStdExtDirExt;
use fn_error_context::context;
use rustix::fs::fsync;

use crate::composefs_consts::TYPE1_ENT_PATH;
use crate::parsers::bls_config::{BLSConfig, BLSConfigType, parse_bls_config};

/// The file under `boot/grub2` that holds the rendered menu.
pub(crate) const BLS_MENU_CFG: &str = "bootc-bls.cfg";

/// Quote a string for GRUB script, which follows the shell's single quoting.
fn grub_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// Render menu entries for `entries`, given as (file name, config), in the order
/// GRUB lists them: file name descending, as `blscfg` does and as bootc names
/// them for (see bootc issue #2221), so the primary entry is the default.
pub(crate) fn render_grub_bls_menu(mut entries: Vec<(String, BLSConfig)>) -> Result<String> {
    entries.sort_by(|a, b| b.0.cmp(&a.0));

    let mut out = String::from("# Generated by bootc from loader/entries; do not edit.\n");
    for (file_name, cfg) in &entries {
        let BLSConfigType::NonEFI {
            linux,
            initrd,
            options,
        } = &cfg.cfg_type
        else {
            anyhow::bail!("{file_name}: not a linux entry");
        };
        let id = format!("bootc-{}", file_name.trim_end_matches(".conf"));
        let title = cfg
            .title
            .clone()
            .unwrap_or_else(|| cfg.version().to_string());

        writeln!(
            out,
            "menuentry {} --id {} {{",
            grub_quote(&title),
            grub_quote(&id)
        )?;
        match options.as_deref() {
            Some(opts) => writeln!(out, "    linux {linux} {opts}")?,
            None => writeln!(out, "    linux {linux}")?,
        }
        if !initrd.is_empty() {
            let initrds: Vec<String> = initrd.iter().map(|p| p.to_string()).collect();
            writeln!(out, "    initrd {}", initrds.join(" "))?;
        }
        writeln!(out, "}}")?;
    }
    Ok(out)
}

/// Rewrite `grub2/bootc-bls.cfg` from the live `loader/entries`.
///
/// Called wherever the live entries change: install, finalize, rollback and
/// delete. Atomic, so GRUB reads either the old menu or the new one.
#[context("Writing GRUB menu for BLS entries")]
pub(crate) fn sync_grub_bls_menu(boot_dir: &Dir) -> Result<()> {
    let mut entries = vec![];
    for entry in boot_dir.read_dir(TYPE1_ENT_PATH)? {
        let entry = entry?;
        let file_name = entry.file_name();
        let Some(file_name) = file_name.to_str() else {
            anyhow::bail!("Found non UTF-8 characters in filename");
        };
        if !file_name.ends_with(".conf") {
            continue;
        }
        let mut contents = String::new();
        entry
            .open()?
            .read_to_string(&mut contents)
            .with_context(|| format!("Reading {file_name}"))?;
        let cfg = parse_bls_config(&contents).with_context(|| format!("Parsing {file_name}"))?;
        entries.push((file_name.to_string(), cfg));
    }

    let menu = render_grub_bls_menu(entries)?;
    // At install the bootloader may not have written its own config yet.
    boot_dir.create_dir_all("grub2").context("Creating grub2")?;
    let grub_dir = boot_dir.open_dir("grub2").context("Opening grub2")?;
    grub_dir
        .atomic_replace_with(BLS_MENU_CFG, |f| f.write_all(menu.as_bytes()))
        .with_context(|| format!("Writing {BLS_MENU_CFG}"))?;
    fsync(grub_dir.reopen_as_ownedfd()?).context("fsync")?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cfg(s: &str) -> BLSConfig {
        parse_bls_config(s).unwrap()
    }

    #[test]
    fn primary_first_with_options_and_initrd() {
        let booted = cfg(
            "title App\nversion 1\nlinux /a/vmlinuz\ninitrd /a/initrd\noptions root=UUID=x composefs=aaa rw\n",
        );
        let new = cfg(
            "title App\nversion 2\nlinux /b/vmlinuz\ninitrd /b/initrd\noptions root=UUID=x composefs=bbb rw\n",
        );
        let menu = render_grub_bls_menu(vec![
            ("bootc_app-1-0.conf".into(), booted),
            ("bootc_app-2-1.conf".into(), new),
        ])
        .unwrap();
        let first = menu.find("composefs=bbb").unwrap();
        let second = menu.find("composefs=aaa").unwrap();
        assert!(
            first < second,
            "the primary entry must be the default:\n{menu}"
        );
        assert!(menu.contains("menuentry 'App' --id 'bootc-bootc_app-2-1' {\n    linux /b/vmlinuz root=UUID=x composefs=bbb rw\n    initrd /b/initrd\n}\n"), "{menu}");
    }

    #[test]
    fn a_quote_in_the_title_stays_one_word() {
        let c = cfg("title It's\nversion 1\nlinux /a/vmlinuz\n");
        let menu = render_grub_bls_menu(vec![("x.conf".into(), c)]).unwrap();
        assert!(
            menu.contains(r"menuentry 'It'\''s' --id 'bootc-x' {"),
            "{menu}"
        );
        assert!(!menu.contains("initrd"), "{menu}");
    }

    #[test]
    fn a_uki_entry_is_refused() {
        let c = cfg("title U\nversion 1\nuki /EFI/Linux/u.efi\n");
        assert!(render_grub_bls_menu(vec![("u.conf".into(), c)]).is_err());
    }
}
